import fs from 'node:fs/promises';
import sharp from 'sharp';
const directory=new URL('../public/assets/textures/robots/boss/',import.meta.url);
const files=(await fs.readdir(directory)).filter(file=>/^b_\d+\.png$/.test(file)).sort((a,b)=>a.localeCompare(b,undefined,{numeric:true}));
if(!files.length)throw Error('No boss atlases found');
for(const file of files){const meta=await sharp(new URL(file,directory).pathname).metadata();if(meta.width!==256||meta.height!==256)throw Error('Boss atlas must be 256x256: '+file);}
await fs.writeFile(new URL('../src/boss/texture-list.js',import.meta.url),'// Generated by scripts/prepare-boss-textures.mjs.\nexport const BOSS_TEXTURES = '+JSON.stringify(files.map(file=>'assets/textures/robots/boss/'+file))+';\n');
