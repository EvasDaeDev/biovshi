import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('location editor draws, moves, deletes and round-trips a symmetrical plan',async t=>{
 const html=await fs.readFile(new URL('../bio_editor/index.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://example.test/biovshi/test/bio_editor/'});
 t.after(()=>dom.window.close());
 const {document}=dom.window;
 const $=id=>document.getElementById(id);
 t.mock.method(globalThis,'fetch',async url=>{
  assert.equal(url.href,'https://example.test/biovshi/test/locations/active.json');
  return {ok:true,json:async()=>({version:1,active:['ward']})};
 });
 const previous={document:globalThis.document,DOMPoint:globalThis.DOMPoint,Option:globalThis.Option};
 t.after(()=>Object.assign(globalThis,previous));
 globalThis.document=document;
 globalThis.Option=dom.window.Option;
 globalThis.DOMPoint=class{constructor(x,y){this.x=x;this.y=y;}matrixTransform(){return this;}};
 const svg=$('blueprint');
 svg.getScreenCTM=()=>({inverse:()=>({})});
 let pointer;
 svg.setPointerCapture=id=>{pointer=id;};
 svg.hasPointerCapture=id=>pointer===id;
 svg.releasePointerCapture=()=>{pointer=undefined;};
 const objects=()=>[...document.querySelectorAll('.object')];
 const tool=name=>document.querySelector('[data-tool="'+name+'"]').click();
 const gesture=(start,end,target=svg)=>{
  const [x,y]=start,[bx,by]=end;
  const dispatch=(where,name,clientX,clientY)=>{
   const e=new dom.window.MouseEvent(name,{bubbles:true,button:0,clientX,clientY});
   Object.defineProperty(e,'pointerId',{value:1});
   where.dispatchEvent(e);
  };
  dispatch(target,'pointerdown',x,y);
  dispatch(svg,'pointermove',bx,by);
  dispatch(svg,'pointerup',bx,by);
 };
 await import('../Editors/location-editor.js');
 await new Promise(resolve=>setImmediate(resolve));
 assert.deepEqual([...$('catalog').options].map(option=>option.value),['','ward']);

 tool('wall');
 $('mirror-x').click();
 gesture([100,150],[100,300]);
 assert.equal(objects().length,2);
 $('mirror-x').click();
 $('mirror-y').click();
 tool('obstacle');
 gesture([220,180],[300,250]);
 assert.equal(objects().length,4);
 $('mirror-x').click();
 gesture([40,40],[80,80]);
 assert.equal(objects().length,8);
 tool('select');
 gesture([60,60],[80,80],objects()[4]);
 assert.equal(objects()[4].getAttribute('points'),'60,60 100,60 100,100 60,100');
 $('delete').click();
 assert.equal(objects().length,4);
 $('undo').click();
 assert.equal(objects().length,8);
 $('check').click();
 assert.ok(document.querySelectorAll('.gap').length>0);
 assert.equal(document.querySelectorAll('.spawn').length,4);

 let exported,filename;
 t.mock.method(URL,'createObjectURL',blob=>{exported=blob;return 'blob:test';});
 t.mock.method(URL,'revokeObjectURL',()=>{});
 t.mock.method(dom.window.HTMLAnchorElement.prototype,'click',function(){filename=this.download;});
 $('export').click();
 const json=await exported.text();
 assert.equal(filename,'new-arena.json');
 assert.equal(JSON.parse(json).objects.length,8);
 $('new-map').click();
 assert.equal(objects().length,0);
 Object.defineProperty($('file'),'files',{value:[new File([json],filename,{type:'application/json'})]});
 $('file').dispatchEvent(new dom.window.Event('change'));
 await new Promise(resolve=>setImmediate(resolve));
 assert.equal(objects().length,8);
 $('new-map').click();
 $('width').value='900';
 $('width').dispatchEvent(new dom.window.Event('change'));
 $('height').value='500';
 $('height').dispatchEvent(new dom.window.Event('change'));
 $('mirror-x').click();
 tool('circle');
 gesture([700,130],[760,130]);
 assert.equal(objects().length,2);
 assert.equal(objects()[0].getAttribute('points').split(' ').length,48);
 assert.ok(objects()[1].getAttribute('points').includes('760,370'));
 $('mirror-y').click();
 tool('polygon');
 for(const p of [[280,100],[550,100],[550,180],[390,180],[390,360],[280,360],[280,100]])gesture(p,p);
 assert.equal(objects().length,3);
 assert.equal(objects()[2].getAttribute('points'),'280,100 550,100 550,180 390,180 390,360 280,360');
 $('export').click();
 const rectangular=JSON.parse(await exported.text());
 assert.deepEqual([rectangular.width,rectangular.height],[900,500]);
 assert.equal(rectangular.objects.length,3);
 $('new-map').click();
 tool('obstacle');
 gesture([200,200],[300,250]);
 $('mirror-x').click();
 $('rotate-right').click();
 const adjusted=objects()[0].getAttribute('points').split(' ').map(p=>p.split(',').map(Number));
 const angle=Math.atan2(adjusted[1][1]-adjusted[0][1],adjusted[1][0]-adjusted[0][0])*180/Math.PI;
 assert.ok(Math.abs(angle-5)<1e-8);
 assert.equal(objects().length,2,'rotation reflects the selected object');
 $('mirror-x').click();
 tool('spawn-player');
 gesture([100,100],[100,100]);
 tool('spawn-opponent');
 gesture([570,200],[570,200]);
 gesture([540,510],[540,510]);
 assert.equal(document.querySelectorAll('.spawn-marker').length,3);
 tool('select');
 let enemy=document.querySelector('[data-spawn-role="opponent"] circle');
 gesture([570,200],[590,150],enemy);
 tool('mannequin');
 gesture([300,300],[320,330]);
 $('rotate-left').click();
 const mannequin=document.querySelector('.patient-mannequin');
 assert.equal(mannequin.getAttribute('transform'),'translate(320 330) rotate(-5)');
 assert.ok(mannequin.querySelectorAll('line,circle').length>=16);
 const previousExport=exported;
 $('export').click();
 assert.notEqual(exported,previousExport,$('status').textContent);
 const edited=JSON.parse(await exported.text());
 assert.deepEqual(edited.towerSpawns,{player:[100,100],opponents:[[590,150],[540,510]]});
 assert.equal(Object.hasOwn(edited,'mannequin'),false);
 assert.equal(edited.objects.length,2);
 $('new-map').click();
 tool('obstacle');
 gesture([250,250],[350,300]);
 tool('select');
 gesture([300,270],[300,270],objects()[0]);
 assert.equal(document.querySelector('.transform-gizmo').getAttribute('transform'),'translate(300 275)');
 $('edit-pivot').click();
 const handle=name=>document.querySelector('[data-transform="'+name+'"]');
 gesture([300,275],[250,250],handle('pivot'));
 assert.equal(objects()[0].getAttribute('points'),'250,250 350,250 350,300 250,300');
 $('edit-pivot').click();
 const anglePoint=degrees=>[250+42*Math.cos(degrees*Math.PI/180),250+42*Math.sin(degrees*Math.PI/180)];
 gesture(anglePoint(0),anglePoint(7),handle('rotate'));
 let points=objects()[0].getAttribute('points').split(' ').map(p=>p.split(',').map(Number));
 assert.deepEqual(points[0],[250,250]);
 assert.ok(Math.abs(Math.atan2(points[1][1]-250,points[1][0]-250)*180/Math.PI-5)<1e-8);
 gesture([215,215],[180,180],handle('scale'));
 points=objects()[0].getAttribute('points').split(' ').map(p=>p.split(',').map(Number));
 assert.ok(Math.abs(Math.hypot(points[1][0]-250,points[1][1]-250)-200)<1e-8);
 gesture([303,250],[333,290],handle('x'));
 $('export').click();
 const withPivot=JSON.parse(await exported.text());
 assert.deepEqual(withPivot.objects[0].pivot,[280,250]);
 assert.deepEqual(withPivot.objects[0].points[0],[280,250]);
 $('reset-pivot').click();
 $('export').click();
 assert.equal(Object.hasOwn(JSON.parse(await exported.text()).objects[0],'pivot'),false);
});
